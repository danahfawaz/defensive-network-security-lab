"""Offline packet-level policy simulator.

Given the parsed configurations (:mod:`ciscoaudit.policy.network`) and a flow (:mod:`ciscoaudit.policy.flow`) it follows the
packet the way the routers would handle it:

    ingress ACL -> (outside->inside NAT) -> local delivery or routing -> (inside->outside NAT) -> egress ACL -> next device

and then follows the reply the same way, because an ACL set that lets a request through but drops the answer is a broken
service.  What it models, and nothing else:

* IPv4 extended/standard ACLs, evaluated by :class:`ciscoaudit.acl.ACL` (first match wins, implicit deny, ``established``);
* connected and static routes (longest prefix, ``Null0`` discard), no routing protocols;
* static NAT and PAT with an interface address (``ip nat inside source ...``);
* VTY ``transport input`` and ``access-class`` for traffic addressed to a device, and the HTTP server switch;
* Layer 2 inside one subnet: hosts in the same zone reach each other directly, with no router and therefore no ACL.

What it does not model: TCP state (``established`` is matched on the ACK flag like IOS does, so crafted packets get through
exactly as they would on a real router), fragments, ICMP errors generated by the network, DHCP/ARP behaviour, host
firewalls, services running on hosts, and anything about how Packet Tracer itself behaves.  A verdict from this module
says what the *configuration* does; it is not a Packet Tracer result.
"""

from __future__ import annotations

import ipaddress
from dataclasses import dataclass, field, replace

from ..acl import Packet
from .flow import ICMP_TYPES, FlowSpec
from .network import Network, RouterInterface, RouterModel, SwitchModel
from .topology import Zone

IPv4 = ipaddress.IPv4Address
MAX_HOPS = 10
BROADCAST = IPv4("255.255.255.255")
ICMP_ECHO, ICMP_ECHO_REPLY = 8, 0
DELIVERED, DENIED, DROPPED, REFUSED = "delivered", "denied", "dropped", "refused"


@dataclass(frozen=True)
class Hop:
    """One thing that happened to the packet."""

    device: str
    stage: str  # l2 | acl | nat | route | local | deliver
    verdict: str  # permit | deny | info | drop
    text: str

    def __str__(self) -> str:
        return f"{self.device}: {self.text}"


@dataclass
class Leg:
    """The journey of one packet (the request or the reply)."""

    packet: Packet
    outcome: str = DROPPED  # delivered | denied | dropped | refused
    hops: list[Hop] = field(default_factory=list)
    blocked_by: str | None = None  # ACL name | "route" | "vty" | "no-service"
    at: str | None = None  # device that stopped the packet
    reached: str | None = None  # device or host that received it
    final: Packet | None = None  # the packet as it arrived (after NAT)
    pat_sessions: dict[int, int] = field(default_factory=dict)  # inside-global -> inside-local, created by PAT
    reason: str = ""

    @property
    def delivered(self) -> bool:
        return self.outcome == DELIVERED


@dataclass
class FlowResult:
    flow: FlowSpec
    src_ip: str
    dst_ip: str
    forward: Leg
    reply: Leg | None = None

    @property
    def delivered(self) -> bool:
        return self.forward.delivered and (self.reply is None or self.reply.delivered)

    @property
    def stopped(self) -> Leg | None:
        if not self.forward.delivered:
            return self.forward
        if self.reply is not None and not self.reply.delivered:
            return self.reply
        return None

    @property
    def blocked_by(self) -> str | None:
        leg = self.stopped
        return leg.blocked_by if leg else None

    @property
    def at(self) -> str | None:
        leg = self.stopped
        return leg.at if leg else None

    @property
    def phase(self) -> str:
        """Which packet was stopped: ``request`` or ``reply`` (``-`` when nothing was stopped)."""
        if self.stopped is None:
            return "-"
        return "request" if self.stopped is self.forward else "reply"

    def summary(self) -> str:
        if self.delivered:
            back = " and the reply returns" if self.reply is not None else ""
            return f"delivered to {self.forward.reached or 'the subnet (no known host)'}{back}"
        leg = self.stopped
        assert leg is not None
        what = "request" if leg is self.forward else "reply"
        return f"{what} {leg.outcome} at {leg.at}: {leg.reason}"

    def to_dict(self, *, trace: bool = True) -> dict:
        out: dict = {
            "flow": str(self.flow), "source": self.src_ip, "destination": self.dst_ip,
            "verdict": "delivered" if self.delivered else "blocked", "phase": self.phase,
            "blocked_by": self.blocked_by, "at": self.at, "summary": self.summary(),
        }
        if trace:
            out["request"] = [str(h) for h in self.forward.hops]
            out["reply"] = [str(h) for h in self.reply.hops] if self.reply is not None else None
        return out


@dataclass(frozen=True)
class Node:
    """Something that can send or receive: a host, a managed device or a bare address."""

    kind: str  # host | router | switch | ip
    name: str | None
    ip: IPv4


@dataclass
class _Ctx:
    hops: list[Hop]
    reply: bool = False
    pat_sessions: dict[int, int] = field(default_factory=dict)
    visited: set[tuple[str, str]] = field(default_factory=set)


def _ip(value: int | IPv4) -> IPv4:
    return value if isinstance(value, IPv4) else IPv4(value)


class Simulator:
    def __init__(self, network: Network) -> None:
        self.net = network
        self.topology = network.topology
        self._ips: dict[IPv4, Node] = {}
        for host in self.topology.hosts.values():
            self._ips[host.ip] = Node("host", host.name, host.ip)
        for name, addr in self.topology.management.items():
            kind = "router" if name in network.routers else "switch"
            self._ips.setdefault(addr, Node(kind, name, addr))

    # ------------------------------------------------------------------------------------------------------------
    # names and addresses
    # ------------------------------------------------------------------------------------------------------------

    def resolve(self, text: str) -> Node:
        """A host or device name, or an IPv4 address."""
        if text in self.topology.hosts:
            h = self.topology.hosts[text]
            return Node("host", h.name, h.ip)
        if text in self.net.routers:
            router = self.net.routers[text]
            addr = self.topology.management.get(text) or next((i.ip.ip for i in router.interfaces.values() if i.ip), None)
            if addr is None:
                raise ValueError(f"{text}: the router has no address")
            return Node("router", text, addr)
        if text in self.net.switches:
            addr = self.net.switches[text].management_ip()
            if addr is None:
                raise ValueError(f"{text}: the switch has no single management address")
            return Node("switch", text, addr)
        try:
            ip = IPv4(text)
        except ValueError:
            raise ValueError(f"{text!r} is neither a host, a device nor an IPv4 address") from None
        return self._ips.get(ip) or Node("ip", None, ip)

    def _owner(self, ip: IPv4) -> tuple[RouterModel, RouterInterface] | None:
        for router in self.net.routers.values():
            iface = router.interface_with_ip(ip)
            if iface is not None and iface.up:
                return router, iface
        return None

    def is_router_address(self, ip: IPv4 | str) -> bool:
        """True if ``ip`` is configured on an interface of one of the routers (such traffic is addressed to the router)."""
        return self._owner(IPv4(str(ip))) is not None

    def _node_at(self, ip: IPv4) -> Node | None:
        node = self._ips.get(ip)
        if node is not None:
            return node
        for sw in self.net.switches.values():
            if sw.management_ip() == ip:
                return Node("switch", sw.name, ip)
        return None

    def _attachment(self, node: Node) -> tuple[ipaddress.IPv4Network, IPv4 | None, Zone | None]:
        """The subnet a node sits on and the gateway it uses to leave it."""
        if node.kind == "switch":
            sw = self.net.switches[node.name or ""]
            svis = [a for v, a in sw.svis.items() if sw.svi_up.get(v) and a.ip == node.ip]
            if not svis:
                raise ValueError(f"{node.name}: no management SVI with {node.ip}")
            return svis[0].network, sw.default_gateway, None
        zone = self.topology.zone_of(node.ip)
        if zone is None:
            raise ValueError(f"{node.ip} is not inside any zone of the topology")
        return zone.subnet, zone.gateway, zone

    # ------------------------------------------------------------------------------------------------------------
    # public API
    # ------------------------------------------------------------------------------------------------------------

    def run(self, flow: FlowSpec) -> FlowResult:
        src, dst = self.resolve(flow.src), self.resolve(flow.dst)
        if src.kind == "ip" and flow.spoof is None and src.name is None:
            raise ValueError(f"{flow.src}: a bare source address needs a known sender")
        sent_from = IPv4(flow.spoof) if flow.spoof else src.ip
        pkt = self._packet(flow, sent_from, dst.ip)
        forward = self._send(src, pkt, _Ctx(hops=[]))
        result = FlowResult(flow, str(sent_from), str(dst.ip), forward)
        if forward.delivered and flow.expects_reply and forward.reached is not None:
            replier = self.resolve(forward.reached)
            reply_pkt = self._reply_packet(forward.final or pkt)
            reply = self._send(replier, reply_pkt, _Ctx(hops=[], reply=True, pat_sessions=dict(forward.pat_sessions)))
            if reply.delivered and reply.reached != src.name:
                reply.outcome, reply.blocked_by, reply.at = DROPPED, "route", reply.reached
                reply.reason = f"the reply reached {reply.reached or 'an unknown host'} instead of {src.name}"
            result.reply = reply
        return result

    # ------------------------------------------------------------------------------------------------------------
    # packets
    # ------------------------------------------------------------------------------------------------------------

    @staticmethod
    def _packet(flow: FlowSpec, src: IPv4, dst: IPv4) -> Packet:
        if flow.proto == "icmp":
            return Packet("icmp", int(src), int(dst), icmp_type=ICMP_TYPES[flow.icmp_type or "echo"], icmp_code=0)
        return Packet(flow.proto, int(src), int(dst), sport=flow.source_port, dport=flow.dport, tcp_ack=flow.ack)

    @staticmethod
    def _reply_packet(pkt: Packet) -> Packet:
        if pkt.proto == "icmp":
            return Packet("icmp", pkt.dst, pkt.src, icmp_type=ICMP_ECHO_REPLY, icmp_code=0)
        return Packet(pkt.proto, pkt.dst, pkt.src, sport=pkt.dport, dport=pkt.sport, tcp_ack=pkt.proto == "tcp")

    # ------------------------------------------------------------------------------------------------------------
    # moving a packet
    # ------------------------------------------------------------------------------------------------------------

    def _send(self, origin: Node, pkt: Packet, ctx: _Ctx) -> Leg:
        leg = Leg(packet=pkt)
        dst = _ip(pkt.dst)
        try:
            if origin.kind == "router":
                router = self.net.routers[origin.name or ""]
                self._walk(router, None, pkt, ctx, leg)
                return leg
            subnet, gateway, _zone = self._attachment(origin)
        except ValueError as exc:
            return self._finish(leg, ctx, DROPPED, "route", origin.name or str(origin.ip), str(exc))

        owner = self._owner(dst)
        if dst == BROADCAST:
            # limited broadcast: only the gateway router can be the receiver
            if gateway is None or self._owner(gateway) is None:
                return self._finish(leg, ctx, DROPPED, "route", origin.name or str(origin.ip), "no gateway for a broadcast")
            router, ingress = self._owner(gateway)  # type: ignore[misc]
            ctx.hops.append(Hop(origin.name or str(origin.ip), "l2", "info", f"broadcast to {router.name} {ingress.name} (the gateway)"))
            self._walk(router, ingress, pkt, ctx, leg)
            return leg
        if dst in subnet and owner is None:
            # same subnet: the switch delivers it directly, no router and no ACL
            ctx.hops.append(Hop(origin.name or str(origin.ip), "l2", "info", f"{dst} is on the same subnet ({subnet}): switched, no router, no ACL"))
            return self._deliver(dst, pkt, ctx, leg, from_device=origin.name or str(origin.ip))
        if dst in subnet and owner is not None:
            router, ingress = owner  # talking to the router's own address on this subnet
        else:
            if gateway is None:
                return self._finish(leg, ctx, DROPPED, "route", origin.name or str(origin.ip), "no default gateway")
            gw = self._owner(gateway)
            if gw is None:
                return self._finish(leg, ctx, DROPPED, "route", origin.name or str(origin.ip), f"gateway {gateway} does not answer")
            router, ingress = gw
        ctx.hops.append(Hop(origin.name or str(origin.ip), "l2", "info", f"sends to its gateway {router.name} {ingress.name} ({ingress.ip.ip})"))
        self._walk(router, ingress, pkt, ctx, leg)
        return leg

    def _walk(self, router: RouterModel, ingress: RouterInterface | None, pkt: Packet, ctx: _Ctx, leg: Leg) -> None:
        for _ in range(MAX_HOPS):
            key = (router.name, ingress.name if ingress else "-")
            if key in ctx.visited:
                self._finish(leg, ctx, DROPPED, "route", router.name, "routing loop")
                return
            ctx.visited.add(key)
            nxt = self._router_step(router, ingress, pkt, ctx, leg)
            if nxt is None:
                return
            router, ingress, pkt = nxt
        self._finish(leg, ctx, DROPPED, "route", router.name, f"more than {MAX_HOPS} hops")

    # -- one router ------------------------------------------------------------------------------------------------
    def _router_step(self, r: RouterModel, ingress: RouterInterface | None, pkt: Packet, ctx: _Ctx,
                     leg: Leg) -> tuple[RouterModel, RouterInterface | None, Packet] | None:
        # 1. inbound ACL
        if ingress is not None:
            if ingress.acl_in:
                if not self._acl(r, ingress, ingress.acl_in, "in", pkt, ctx, leg):
                    return None
            else:
                ctx.hops.append(Hop(r.name, "acl", "info", f"{ingress.name} in: no ACL, everything is permitted"))

        # 2. NAT outside -> inside happens before routing
        if ingress is not None and ingress.nat == "outside":
            pkt = self._dnat(r, pkt, ctx)

        dst = _ip(pkt.dst)
        # 3. addressed to the router itself
        local = (ingress is not None and dst == BROADCAST) or self._is_own(r, dst)
        if local:
            self._local(r, ingress, pkt, ctx, leg)
            return None

        # 4. routing
        kind, how = r.route(dst)
        if kind == "none" or how is None:
            self._finish(leg, ctx, DROPPED, "route", r.name, f"no route to {dst}")
            return None
        if kind == "static" and how.discard:  # type: ignore[union-attr]
            self._finish(leg, ctx, DROPPED, "route", r.name, f"{dst} matches {how.network} -> Null0 (discard route)")  # type: ignore[union-attr]
            return None
        egress, next_hop = self._egress(r, kind, how, dst)
        if egress is None:
            self._finish(leg, ctx, DROPPED, "route", r.name, f"next hop for {dst} is not reachable")
            return None
        via = "connected" if kind == "connected" else f"static route {how.network}"  # type: ignore[union-attr]
        ctx.hops.append(Hop(r.name, "route", "info", f"{dst} via {via} -> {egress.name}"
                            + (f", next hop {next_hop}" if next_hop != dst else "")))

        # 5. NAT inside -> outside happens after routing
        if ingress is not None and ingress.nat == "inside" and egress.nat == "outside":
            pkt = self._snat(r, pkt, ctx, leg)

        # 6. outbound ACL
        if egress.acl_out and not self._acl(r, egress, egress.acl_out, "out", pkt, ctx, leg):
            return None

        # 7. next device
        owner = self._owner(next_hop)
        if owner is not None and owner[0] is not r:
            ctx.hops.append(Hop(r.name, "deliver", "info", f"forwards to {owner[0].name} {owner[1].name} ({next_hop})"))
            return owner[0], owner[1], pkt
        if next_hop != dst and owner is None:
            self._finish(leg, ctx, DROPPED, "route", r.name, f"next hop {next_hop} is not a device of this network")
            return None
        self._deliver(dst, pkt, ctx, leg, from_device=r.name)
        return None

    @staticmethod
    def _is_own(r: RouterModel, ip: IPv4) -> bool:
        iface = r.interface_with_ip(ip)
        return iface is not None and iface.up

    @staticmethod
    def _egress(r: RouterModel, kind: str, how, dst: IPv4) -> tuple[RouterInterface | None, IPv4]:
        if kind == "connected":
            return how, dst
        route = how
        if route.next_hop is not None:
            return r.connected_interface(route.next_hop), route.next_hop
        iface = r.interfaces.get(route.interface or "")
        return (iface if iface is not None and iface.up else None), dst

    # -- ACL -------------------------------------------------------------------------------------------------------
    def _acl(self, r: RouterModel, iface: RouterInterface, name: str, direction: str, pkt: Packet, ctx: _Ctx,
             leg: Leg) -> bool:
        acl = r.acls.get(name)
        where = f"{iface.name} {direction}"
        if acl is None:
            ctx.hops.append(Hop(r.name, "acl", "info", f"{where}: ACL {name} is not defined, IOS permits everything"))
            return True
        verdict = acl.evaluate(pkt)
        if verdict.ace is not None:
            entry = f"'{verdict.ace.text}' (line {verdict.ace.line.no})"
        elif verdict.reason == "empty-acl-permit":
            entry = "ACL has no entries, IOS permits everything"
        else:
            entry = "no entry matches: implicit deny"
        ctx.hops.append(Hop(r.name, "acl", verdict.action, f"{where}: ACL {name} {'permits' if verdict.action == 'permit' else 'denies'} - {entry}"))
        if verdict.action == "permit":
            return True
        self._finish(leg, ctx, DENIED, name, r.name, f"{where} ACL {name}: {entry}")
        return False

    # -- NAT -------------------------------------------------------------------------------------------------------
    def _dnat(self, r: RouterModel, pkt: Packet, ctx: _Ctx) -> Packet:
        dst = _ip(pkt.dst)
        for entry in r.nat_static:
            if entry.outside == dst:
                ctx.hops.append(Hop(r.name, "nat", "info", f"static NAT {entry.outside} -> {entry.inside} (destination, before routing)"))
                return replace(pkt, dst=int(entry.inside))
        if pkt.dst in ctx.pat_sessions:
            inside = ctx.pat_sessions[pkt.dst]
            ctx.hops.append(Hop(r.name, "nat", "info", f"PAT session: {dst} -> {_ip(inside)} (reply to a connection opened from inside)"))
            return replace(pkt, dst=inside)
        return pkt

    def _snat(self, r: RouterModel, pkt: Packet, ctx: _Ctx, leg: Leg) -> Packet:
        src = _ip(pkt.src)
        for entry in r.nat_static:
            if entry.inside == src:
                ctx.hops.append(Hop(r.name, "nat", "info", f"static NAT {entry.inside} -> {entry.outside} (source, after routing)"))
                return replace(pkt, src=int(entry.outside))
        for pat in r.nat_pat:
            acl = r.acls.get(pat.acl)
            iface = r.interfaces.get(pat.interface)
            if acl is None or iface is None or iface.ip is None:
                continue
            if acl.evaluate(pkt).action == "permit":
                ctx.hops.append(Hop(r.name, "nat", "info", f"PAT: {src} -> {iface.ip.ip} (ACL {pat.acl}, interface {pat.interface})"))
                leg.pat_sessions[int(iface.ip.ip)] = pkt.src
                ctx.pat_sessions[int(iface.ip.ip)] = pkt.src
                return replace(pkt, src=int(iface.ip.ip))
        ctx.hops.append(Hop(r.name, "nat", "info", f"{src} is not translated: it leaves the outside interface with its private address"))
        return pkt

    # -- delivery --------------------------------------------------------------------------------------------------
    def _deliver(self, dst: IPv4, pkt: Packet, ctx: _Ctx, leg: Leg, *, from_device: str) -> Leg:
        node = self._node_at(dst)
        if node is None:
            leg.final = pkt
            ctx.hops.append(Hop(from_device, "deliver", "info", f"{dst} is on the connected subnet but no known host has this address"))
            return self._finish(leg, ctx, DELIVERED, None, None, "", reached=None)
        if node.kind == "switch":
            return self._control_plane(self.net.switches[node.name or ""], node.name or "", pkt, ctx, leg)
        if node.kind == "router":
            router = self.net.routers[node.name or ""]
            owner = self._owner(dst)
            if owner is not None:  # a router address reached from a neighbour: continue on that router
                self._walk(owner[0], owner[1], pkt, ctx, leg)
                return leg
            return self._finish(leg, ctx, DROPPED, "route", router.name, f"{router.name} does not answer on {dst}")
        leg.final = pkt
        ctx.hops.append(Hop(from_device, "deliver", "permit", f"delivered to {node.name} ({dst})"))
        return self._finish(leg, ctx, DELIVERED, None, None, "", reached=node.name)

    def _local(self, r: RouterModel, ingress: RouterInterface | None, pkt: Packet, ctx: _Ctx, leg: Leg) -> None:
        dst = _ip(pkt.dst)
        leg.final = pkt
        if ctx.reply:
            ctx.hops.append(Hop(r.name, "local", "permit", f"reply addressed to {r.name} itself ({dst})"))
            self._finish(leg, ctx, DELIVERED, None, None, "", reached=r.name)
            return
        self._control_plane(r, r.name, pkt, ctx, leg, ingress=ingress)

    def _control_plane(self, dev: RouterModel | SwitchModel, name: str, pkt: Packet, ctx: _Ctx, leg: Leg, *,
                       ingress: RouterInterface | None = None) -> Leg:
        """Traffic addressed to a router or switch itself: is there a service, and does it accept this source?"""
        leg.final = pkt
        dst = _ip(pkt.dst)
        if ctx.reply:
            ctx.hops.append(Hop(name, "local", "permit", f"reply addressed to {name} itself ({dst})"))
            return self._finish(leg, ctx, DELIVERED, None, None, "", reached=name)
        if pkt.proto == "icmp":
            if pkt.icmp_type == ICMP_ECHO:
                ctx.hops.append(Hop(name, "local", "permit", f"{name} answers ICMP echo on {dst}"))
                return self._finish(leg, ctx, DELIVERED, None, None, "", reached=name)
            return self._refuse(leg, ctx, name, "no-service", f"{name} does not act on this ICMP message")
        if pkt.proto == "udp" and pkt.dport == 67 and (dst == BROADCAST or ingress is not None):
            if ingress is not None and isinstance(dev, RouterModel) and self._dhcp_pool_for(dev, ingress):
                ctx.hops.append(Hop(name, "local", "permit", f"{name} is the DHCP server for {ingress.network}"))
                return self._finish(leg, ctx, DELIVERED, None, None, "", reached=name)
            return self._refuse(leg, ctx, name, "no-service", f"{name} has no DHCP pool for this subnet")
        if pkt.proto == "tcp" and pkt.dport in (22, 23):
            proto = "ssh" if pkt.dport == 22 else "telnet"
            return self._vty(dev, name, proto, pkt, ctx, leg)
        if pkt.proto == "tcp" and pkt.dport in (80, 443):
            key = ("ip", "http", "server") if pkt.dport == 80 else ("ip", "http", "secure-server")
            on, line = dev.cfg.state(*key)
            if on:
                ctx.hops.append(Hop(name, "local", "permit", f"{name}: '{line.text}' - the web server accepts the connection"))
                return self._finish(leg, ctx, DELIVERED, None, None, "", reached=name)
            return self._refuse(leg, ctx, name, "no-service", f"{name} has no web server enabled on tcp/{pkt.dport}")
        proto_txt = f"{pkt.proto}/{pkt.dport}" if pkt.dport is not None else pkt.proto
        return self._refuse(leg, ctx, name, "no-service", f"{name} has no service on {proto_txt}")

    @staticmethod
    def _dhcp_pool_for(r: RouterModel, ingress: RouterInterface) -> bool:
        for line in r.cfg.top("ip", "dhcp", "pool"):
            net = line.child_starting("network")
            if net and len(net.words) >= 3:
                try:
                    if ipaddress.IPv4Network(f"{net.words[1]}/{net.words[2]}", strict=False) == ingress.network:
                        return True
                except ValueError:
                    continue
        return False

    def _vty(self, dev: RouterModel | SwitchModel, name: str, proto: str, pkt: Packet, ctx: _Ctx, leg: Leg) -> Leg:
        policies = dev.vty
        if not policies:
            return self._refuse(leg, ctx, name, "no-service", f"{name} has no VTY lines")
        src = _ip(pkt.src)
        reasons = []
        for pol in policies:
            if pol.transport is not None and proto not in pol.transport and "all" not in pol.transport:
                reasons.append(f"{pol.label}: 'transport input {' '.join(sorted(pol.transport))}' does not accept {proto}")
                continue
            if pol.access_class is not None:
                acl = dev.acls.get(pol.access_class)
                if acl is not None and acl.evaluate(Packet("ip", pkt.src, pkt.dst)).action != "permit":
                    reasons.append(f"{pol.label}: 'access-class {pol.access_class} in' does not permit {src}")
                    continue
            via = f", access-class {pol.access_class}" if pol.access_class else ", no access-class"
            ctx.hops.append(Hop(name, "local", "permit", f"{pol.label}: {proto} accepted from {src} (transport {'default (all)' if pol.transport is None else ' '.join(sorted(pol.transport))}{via})"))
            return self._finish(leg, ctx, DELIVERED, None, None, "", reached=name)
        return self._refuse(leg, ctx, name, "vty", "; ".join(dict.fromkeys(reasons)))

    def _refuse(self, leg: Leg, ctx: _Ctx, name: str, by: str, reason: str) -> Leg:
        ctx.hops.append(Hop(name, "local", "deny", reason))
        return self._finish(leg, ctx, REFUSED, by, name, reason)

    @staticmethod
    def _finish(leg: Leg, ctx: _Ctx, outcome: str, by: str | None, at: str | None, reason: str, *, reached: str | None = None) -> Leg:
        leg.outcome, leg.blocked_by, leg.at, leg.reason, leg.reached = outcome, by, at, reason, reached
        if outcome == DROPPED:
            ctx.hops.append(Hop(at or "?", "drop", "drop", reason))
        leg.hops = ctx.hops
        return leg


def format_trace(result: FlowResult) -> str:
    """A human-readable trace, one hop per line."""
    lines = [f"{result.flow}", f"  {result.summary()}"]
    for title, leg in (("request", result.forward), ("reply", result.reply)):
        if leg is None:
            continue
        lines.append(f"  {title}:")
        for no, hop in enumerate(leg.hops, 1):
            lines.append(f"    {no:>2}. {hop}")
    return "\n".join(lines)
