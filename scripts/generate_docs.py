#!/usr/bin/env python3
"""Generate the tables and the diagram in docs/generated/ from topology/topology.yaml.

    python scripts/generate_docs.py            # rewrite docs/generated/*.md, topology.dot and (if Graphviz exists) topology.svg
    python scripts/generate_docs.py --check    # exit 1 if the committed Markdown or .dot file is stale

Nothing here is typed twice: addresses, ports and VLANs come from the topology file, which `ciscoaudit design-check` verifies
against the device configurations.  The SVG is only re-rendered when the `dot` program is installed; --check ignores it
because Graphviz versions lay out slightly differently.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
TOPOLOGY = ROOT / "topology" / "topology.yaml"
OUT = ROOT / "docs" / "generated"

NOTICE = "<!-- Generated by scripts/generate_docs.py from the topology, the scenarios and the configurations. Do not edit by hand. -->\n\n"


def load() -> dict:
    return yaml.safe_load(TOPOLOGY.read_text(encoding="utf-8"))


def table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c).replace("|", "/") for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def addressing(t: dict) -> str:
    zones = t["zones"]
    text = NOTICE + "# Addressing plan\n\n## Security zones\n\n"
    text += table(
        ["Zone", "VLAN", "Subnet", "Gateway (FW-EDGE)", "Interface", "Addressing", "Purpose"],
        [[n, z.get("vlan", "-"), f"`{z['subnet']}`", f"`{z['gateway']}`", z["interface"] or "-" if n != "internet" else "ISP-R Fa0/0",
          z["addressing"], z["description"]] for n, z in zones.items()],
    )
    text += "\n## Hosts\n\n"
    text += table(
        ["Host", "Model", "Zone", "IP address", "Default gateway", "DNS server", "Connects to", "Role"],
        [[n, h["model"], h["zone"], f"`{h['ip']}`" + (" (DHCP)" if zones[h["zone"]]["addressing"] == "dhcp" else ""),
          f"`{zones[h['zone']]['gateway']}`",
          "`172.16.50.20`" if h["zone"] in ("users", "servers", "guest") else "-",
          h["attach"], h["role"]] for n, h in t["hosts"].items()],
    )
    text += "\n## Device management addresses\n\n"
    text += table(["Device", "Management address", "Model", "IOS", "Role"],
                  [[n, f"`{ip}`", t["devices"][n]["model"], t["devices"][n]["ios"], t["devices"][n]["role"]]
                   for n, ip in t["management"].items()])
    nat = t["nat"]
    text += "\n## Address translation\n\n"
    text += f"* PAT (overload) on `{nat['pat']['interface']}` ({nat['pat']['address']}) for: {', '.join(nat['pat']['sources'])}.\n"
    text += f"* Public block `{nat['public_block']}` is routed to FW-EDGE by the ISP and used for static NAT only.\n\n"
    text += table(["Published host", "Inside address", "Public address"],
                  [[s["host"], f"`{s['inside']}`", f"`{s['outside']}`"] for s in nat["static"]])
    text += "\n## Published services (from the Internet)\n\n"
    text += table(["Host", "Protocol", "Ports"],
                  [[s["host"], s["protocol"], ", ".join(str(p) for p in s["ports"])] for s in t["services"]["published"]])
    return text


def cabling(t: dict) -> str:
    text = NOTICE + "# Cabling and port map\n\n"
    text += "Use *straight-through* copper cables for every link except where Packet Tracer's automatic cable picks otherwise.\n\n"
    rows = []
    for link in t["links"]:
        detail = {"trunk": "802.1Q trunk, VLANs " + ",".join(str(v) for v in link.get("vlans", [])),
                  "access": f"access VLAN {link['vlan']}" if "vlan" in link else "access",
                  "routed": "routed point-to-point"}[link["kind"]]
        rows.append([link["a"], link["b"], detail, link["origin"], link.get("note", "")])
    text += table(["End A", "End B", "Type", "Origin", "Note"], rows)
    text += "\n## Devices of the original lab that are no longer used\n\n"
    text += table(["Original device", "Why it was removed"], [[r["pt_label"], " ".join(str(r["reason"]).split())] for r in t["retired"]])
    text += "\n## Device name map (original -> new)\n\n"
    text += table(["Original label", "New hostname", "Model", "Audited"],
                  [[d["pt_label"], n, d["model"], "yes" if d["audited"] else "no (Internet simulation)"] for n, d in t["devices"].items()])
    return text


def dot(t: dict) -> str:
    zones, hosts = t["zones"], t["hosts"]
    colours = {"users": "#dbeafe", "servers": "#e0e7ff", "guest": "#fef3c7", "mgmt": "#dcfce7", "dmz": "#fee2e2", "internet": "#f3f4f6"}
    lines = ["graph lab {", '  rankdir=TB; compound=true; fontname="Helvetica"; nodesep=0.35; ranksep=0.6;',
             '  node [fontname="Helvetica", fontsize=10, shape=box, style="rounded,filled", fillcolor=white];',
             '  edge [fontname="Helvetica", fontsize=8];']
    for dev, d in t["devices"].items():
        shape = "box3d" if d["kind"] == "router" else "box"
        fill = "#fde68a" if dev == "FW-EDGE" else "#e5e7eb"
        lines.append(f'  "{dev}" [shape={shape}, fillcolor="{fill}", label="{dev}\\n{d["model"]}"];')
    by_zone: dict[str, list[str]] = {}
    for n, h in hosts.items():
        by_zone.setdefault(h["zone"], []).append(n)
    for z, members in by_zone.items():
        z_info = zones[z]
        label = f"{z}" + (f" - VLAN {z_info['vlan']}" if "vlan" in z_info else "") + f"\\n{z_info['subnet']}"
        lines.append(f'  subgraph "cluster_{z}" {{ label="{label}"; style="rounded,filled"; fillcolor="{colours.get(z, "#ffffff")}";')
        for m in members:
            lines.append(f'    "{m}" [label="{m}\\n{hosts[m]["ip"]}"];')
        lines.append("  }")
    for link in t["links"]:
        a, b = link["a"].split(":")[0], link["b"].split(":")[0]
        ports = " - ".join(x.split(":")[1] for x in (link["a"], link["b"]) if ":" in x)
        trunk = link["kind"] != "access"
        label = (("trunk " if link["kind"] == "trunk" else "routed ") if trunk else "") + ports
        style = 'penwidth=2, color="#b45309"' if trunk else 'color="#6b7280"'
        lines.append(f'  "{a}" -- "{b}" [label="{label.strip()}", {style}];')
    lines.append("}")
    return "\n".join(lines) + "\n"


def pt_verify() -> str:
    """Every line of the committed configurations whose handling by Packet Tracer was unknown when it was written."""
    text = NOTICE + "# Configuration lines marked [PT-VERIFY]\n\n"
    text += ("Each entry is a `! [PT-VERIFY]` comment in a committed configuration; the configuration it describes follows the marker. They are "
             "standard IOS lines whose handling by Packet Tracer was not known when the configurations were written. The manual Packet "
             "Tracer run ([results](../packet-tracer-validation.md)) exercised several of them (SSH, NTP, syslog, DHCP snooping, Dynamic ARP "
             "Inspection, static NAT with the provider-routed block); "
             "[export-comparison](../../evidence/packet-tracer/export-comparison.md) lists which lines the Packet Tracer running "
             "configuration contains. Lines that were not individually tested are not claimed to have been.\n\n")
    rows = []
    for state in ("hardened", "baseline", "internet-sim"):
        for path in sorted((ROOT / "configs" / state).glob("*.cfg")):
            lines = path.read_text(encoding="utf-8").splitlines()
            for i, line in enumerate(lines):
                if "[PT-VERIFY]" not in line or "Lines marked" in line:
                    continue
                note = line.split("[PT-VERIFY]", 1)[1].strip()
                rows.append([f"`{state}/{path.name}`", i + 1, note])
    text += table(["File", "Line of the marker", "What is unverified"], rows)
    text += f"\n{len(rows)} entries.\n"
    return text


def threat_coverage() -> str:
    """Which scenarios test which threat of docs/threat-model.md."""
    scenarios = yaml.safe_load((ROOT / "scenarios" / "scenarios.yaml").read_text(encoding="utf-8"))["scenarios"]
    names = {}
    for line in (ROOT / "docs" / "threat-model.md").read_text(encoding="utf-8").splitlines():
        if line.startswith("| T") and line[3:5].isdigit():
            cells = [c.strip() for c in line.strip("|").split("|")]
            names[cells[0]] = cells[1]
    text = NOTICE + "# Threat coverage\n\n"
    text += ("Scenario identifiers per threat of [threat-model.md](../threat-model.md). *Simulated* scenarios are judged by the policy "
             "simulator or the auditor from the configuration text; the manual checks (`X-nn`) were observed by hand in Packet Tracer "
             "([results](../packet-tracer-validation.md)).\n\n")
    rows = []
    for tid in sorted(names):
        hits = [sc for sc in scenarios if tid in sc.get("threats", [])]
        sim = [sc["id"] for sc in hits if sc["category"] != "manual"]
        pending = [sc["id"] for sc in hits if sc["category"] == "manual"]
        rows.append([tid, names[tid], len(sim), ", ".join(sim) or "-", ", ".join(pending) or "-"])
    text += table(["Threat", "Description", "Simulated", "Simulated scenarios", "Manual checks (Packet Tracer)"], rows)
    return text


def rules_catalogue() -> str:
    """The auditor's rule catalogue, exactly as `ciscoaudit rules --format markdown` prints it."""
    import contextlib
    import io

    sys.path.insert(0, str(ROOT / "src"))
    from ciscoaudit import cli

    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        cli.main(["rules", "--format", "markdown"])
    return out.getvalue()


def render() -> dict[Path, str]:
    t = load()
    return {OUT / "addressing.md": addressing(t), OUT / "cabling.md": cabling(t), OUT / "topology.dot": dot(t),
            OUT / "pt-verify.md": pt_verify(), OUT / "threat-coverage.md": threat_coverage(),
            OUT / "rules.md": rules_catalogue()}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed files are stale")
    args = ap.parse_args(argv)
    files = render()
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            print("stale (run python scripts/generate_docs.py): " + ", ".join(stale), file=sys.stderr)
            return 1
        print("generated docs are up to date")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
        print("wrote", path.relative_to(ROOT))
    if shutil.which("dot"):
        svg = OUT / "topology.svg"
        subprocess.run(["dot", "-Tsvg", str(OUT / "topology.dot"), "-o", str(svg)], check=True)
        print("wrote", svg.relative_to(ROOT))
    else:
        print("Graphviz 'dot' not found: topology.svg not rendered")
    return 0


if __name__ == "__main__":
    sys.exit(main())
